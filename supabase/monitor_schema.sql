-- VPS Monitor V1: dedicated Supabase PostgreSQL project only.
-- DO NOT run this against FINAL14-Autotrade or any existing application database.
-- Schema is private, not enabled for PostgREST/Data API.
-- This file is a DDL draft; the runtime PostgreSQL adapter must be integrated
-- and verified before promoting the Vibe deployment.
BEGIN;
CREATE SCHEMA IF NOT EXISTS vps_monitor;
REVOKE ALL ON SCHEMA vps_monitor FROM PUBLIC, anon, authenticated;

CREATE TABLE IF NOT EXISTS vps_monitor.server_registry (
 server_id text PRIMARY KEY, name text NOT NULL, host text NOT NULL,
 port integer NOT NULL, role text NOT NULL DEFAULT 'PRIMARY',
 expiry_date date, is_local boolean NOT NULL DEFAULT false,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS vps_monitor.service_registry (
 service_id text PRIMARY KEY, server_id text NOT NULL REFERENCES vps_monitor.server_registry(server_id) ON DELETE CASCADE,
 name text NOT NULL, health_url text, status text NOT NULL DEFAULT 'UNKNOWN',
 last_check timestamptz, last_error text,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS vps_monitor.node_metrics (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 server_id text NOT NULL REFERENCES vps_monitor.server_registry(server_id) ON DELETE CASCADE,
 cpu_pct double precision NOT NULL, ram_used_mb integer NOT NULL,
 ram_total_mb integer NOT NULL, ram_pct double precision NOT NULL,
 disk_used_gb double precision NOT NULL, disk_total_gb double precision NOT NULL,
 disk_pct double precision NOT NULL, net_rx_bytes bigint NOT NULL DEFAULT 0,
 net_tx_bytes bigint NOT NULL DEFAULT 0, uptime_sec bigint NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_monitor_metrics_server_created ON vps_monitor.node_metrics(server_id, created_at DESC);
CREATE TABLE IF NOT EXISTS vps_monitor.heartbeat_log (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sender_id text NOT NULL, receiver_id text NOT NULL, sequence bigint NOT NULL,
 sender_timestamp timestamptz NOT NULL, received_at timestamptz NOT NULL DEFAULT now(),
 status text NOT NULL, latency_ms integer NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_monitor_heartbeat_sender ON vps_monitor.heartbeat_log(sender_id, received_at DESC);
CREATE TABLE IF NOT EXISTS vps_monitor.event_history (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 server_id text NOT NULL, event_type text NOT NULL, severity text NOT NULL,
 message text NOT NULL, details_json text, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_monitor_events_created ON vps_monitor.event_history(created_at DESC);
CREATE TABLE IF NOT EXISTS vps_monitor.alert_state (
 alert_key text PRIMARY KEY, current_state text NOT NULL,
 consecutive_count integer NOT NULL DEFAULT 0, last_alerted_at timestamptz,
 details_json text, updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS vps_monitor.alert_outbox (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 alert_key text NOT NULL, payload_json text NOT NULL,
 status text NOT NULL DEFAULT 'PENDING', attempts integer NOT NULL DEFAULT 0,
 next_retry_at timestamptz NOT NULL DEFAULT now(), last_error text,
 created_at timestamptz NOT NULL DEFAULT now(), delivered_at timestamptz
);
CREATE INDEX IF NOT EXISTS idx_monitor_outbox_retry ON vps_monitor.alert_outbox(status, next_retry_at);
CREATE TABLE IF NOT EXISTS vps_monitor.schema_migrations (
 version integer PRIMARY KEY, applied_at timestamptz NOT NULL DEFAULT now()
);
INSERT INTO vps_monitor.schema_migrations(version) VALUES (1) ON CONFLICT DO NOTHING;

-- Defense in depth; no policies means roles without BYPASSRLS see zero rows.
ALTER TABLE vps_monitor.server_registry ENABLE ROW LEVEL SECURITY;
ALTER TABLE vps_monitor.service_registry ENABLE ROW LEVEL SECURITY;
ALTER TABLE vps_monitor.node_metrics ENABLE ROW LEVEL SECURITY;
ALTER TABLE vps_monitor.heartbeat_log ENABLE ROW LEVEL SECURITY;
ALTER TABLE vps_monitor.event_history ENABLE ROW LEVEL SECURITY;
ALTER TABLE vps_monitor.alert_state ENABLE ROW LEVEL SECURITY;
ALTER TABLE vps_monitor.alert_outbox ENABLE ROW LEVEL SECURITY;
ALTER TABLE vps_monitor.schema_migrations ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ALL TABLES IN SCHEMA vps_monitor FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA vps_monitor FROM PUBLIC, anon, authenticated;
COMMIT;
