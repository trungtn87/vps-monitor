-- Dedicated Vibe Hosting account-wide quotas (not physical host or single container).
-- Keep separate from node_metrics to preserve provenance.
CREATE TABLE IF NOT EXISTS vps_monitor.hosting_quota_metrics (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  server_id text NOT NULL REFERENCES vps_monitor.server_registry(server_id) ON DELETE CASCADE,
  snapshot_at timestamptz NOT NULL,
  collected_at timestamptz NOT NULL DEFAULT now(),
  cpu_used_vcpu double precision NOT NULL,
  cpu_quota_vcpu double precision NOT NULL,
  cpu_pct double precision NOT NULL,
  ram_used_mb double precision NOT NULL,
  ram_quota_mb double precision NOT NULL,
  ram_pct double precision NOT NULL,
  disk_used_mb double precision NOT NULL,
  disk_quota_mb double precision NOT NULL,
  disk_pct double precision NOT NULL,
  apps_json jsonb NOT NULL DEFAULT '[]'::jsonb
);
CREATE INDEX IF NOT EXISTS idx_hosting_quota_server_time
  ON vps_monitor.hosting_quota_metrics (server_id, snapshot_at DESC);
ALTER TABLE vps_monitor.hosting_quota_metrics ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON vps_monitor.hosting_quota_metrics FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE vps_monitor.hosting_quota_metrics_id_seq FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, DELETE ON vps_monitor.hosting_quota_metrics TO vps_monitor_app;
GRANT USAGE, SELECT ON SEQUENCE vps_monitor.hosting_quota_metrics_id_seq TO vps_monitor_app;
CREATE POLICY hosting_quota_private_app
  ON vps_monitor.hosting_quota_metrics FOR ALL TO vps_monitor_app
  USING (true) WITH CHECK (true);
